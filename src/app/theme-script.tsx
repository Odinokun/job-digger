/**
 * Код, який ставить тему до першого фарбування сторінки.
 *
 * Потрібен лише режиму System: явний вибір сервер знає з cookie й пише
 * `data-theme` одразу в HTML. А системну тему знає тільки браузер, і якщо
 * спитати його вже після рендера, користувач із темною системою встигне
 * побачити спалах світлої.
 *
 * Рядок, а не компонент: його вставляють через `dangerouslySetInnerHTML`, бо
 * JSX усередині `<script>` React трактує як текст для екранування.
 *
 * Чому взагалі скрипт, а не медіазапит у CSS: у `@heroui/styles@3.2.7` темні
 * токени оголошені селекторами `.dark, [data-theme="dark"], :host(.dark),
 * :host([data-theme="dark"])` і **жодного** `prefers-color-scheme` у файлі
 * немає. Повторити весь набір змінних бібліотеки під медіазапитом неможливо
 * підтримувати, тому клас ставиться кодом.
 */
const APPLY_SYSTEM_THEME = `
(function () {
  try {
    var dark = window.matchMedia("(prefers-color-scheme: dark)").matches;
    document.documentElement.dataset.theme = dark ? "dark" : "light";
  } catch (error) {
    // Якщо matchMedia недоступний, лишається світла тема з :root - показати
    // сторінку в ній краще, ніж зламати рендер заради оформлення.
  }
})();
`;

/**
 * Тег зі скриптом для режиму System.
 *
 * Серверний компонент: у ньому немає ні стану, ні обробників - лише розмітка,
 * яку браузер виконає сам.
 */
export function ThemeScript() {
  return (
    <script
      // Вміст - власна константа, а не дані користувача: вставляти її так
      // безпечно. Cookie тут не читається взагалі - режим уже визначив сервер.
      dangerouslySetInnerHTML={{ __html: APPLY_SYSTEM_THEME }}
    />
  );
}
